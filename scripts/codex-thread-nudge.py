def sanitized_environment(source=None):
    """Return the small environment app-server needs, excluding credentials."""

    source = os.environ if source is None else source
    allowed = (
        "HOME",
        "PATH",
        "TMPDIR",
        "SHELL",
        "USER",
        "LOGNAME",
        "LANG",
        "LC_ALL",
        "LC_CTYPE",
        "TERM",
        # Desktop-backed app-server tasks require a host-thread context even
        # when thread/resume targets a different (idle) task. Without this,
        # app-server rejects resume and the adapter misclassifies the target
        # as permanently busy.
        "CODEX_THREAD_ID",
        "MERISTEM_LISTENER_CODEX_HOME",
        "MERISTEM_LISTENER_CODEX_SQLITE_HOME",
        "MERISTEM_LISTENER_PROBE",
        # These are non-secret IDs supplied as reviewed activation arguments.
        # The wrapper passes them to each MCP subprocess, where Meristem binds
        # the separately provisioned task credential to the live activation.
        "MERISTEM_MCP_EXPECT_ACTOR_ID",
        "MERISTEM_MCP_LISTENER_ACTIVATION_ID",
        "MERISTEM_MCP_LISTENER_WORK_ITEM_ID",
        "MERISTEM_MCP_LISTENER_ASSIGNMENT_EVENT_ID",
        "XDG_CONFIG_HOME",
        "SSL_CERT_FILE",
        "SSL_CERT_DIR",
        "XPC_FLAGS",
        "XPC_SERVICE_NAME",
        "__CFBundleIdentifier",
        "__CF_USER_TEXT_ENCODING",
    )
    result = {key: source[key] for key in allowed if source.get(key)}
    result.setdefault("PATH", "/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin")
    result["RUST_LOG"] = "error"
    result["RUST_BACKTRACE"] = "0"
    result["NO_COLOR"] = "1"
    return result


def listener_app_server_environment(args, environment=None):
    """Bind vendor state from reviewed adapter arguments, never ambient state."""

    source = dict(os.environ if environment is None else environment)
    bindings = {
        "CODEX_THREAD_ID": args.thread_id,
        "MERISTEM_LISTENER_CODEX_HOME": args.listener_codex_home,
        "MERISTEM_LISTENER_CODEX_SQLITE_HOME": args.listener_codex_sqlite_home,
    }
    source.pop("MERISTEM_LISTENER_PROBE", None)
    if getattr(args, "command", None) == "activate":
        bindings.update(
            {
                "MERISTEM_MCP_EXPECT_ACTOR_ID": args.task_principal_token_id,
                "MERISTEM_MCP_LISTENER_ACTIVATION_ID": args.activation_id,
                "MERISTEM_MCP_LISTENER_WORK_ITEM_ID": args.work_item_id,
                "MERISTEM_MCP_LISTENER_ASSIGNMENT_EVENT_ID": args.assignment_event_id,
            }
        )
    elif getattr(args, "command", None) == "probe":
        bindings["MERISTEM_LISTENER_PROBE"] = "1"
    for key, value in bindings.items():
        if not isinstance(value, str) or not value:
            raise ConfigError()
        source[key] = value
    return source


def validate_listener_paths(args):
    for value in (args.listener_codex_home, args.listener_codex_sqlite_home):
        path = Path(value)
        if not path.is_absolute() or not path.is_dir():
            raise ConfigError()
    if Path(args.listener_codex_home) == Path(args.listener_codex_sqlite_home):
        raise ConfigError()


def find_client_turn(thread, wanted_client_id):
    matches = []
    for turn in thread.get("turns", []):
        if not isinstance(turn, dict):
            continue
        for item in turn.get("items", []):
            if (
                isinstance(item, dict)
                and item.get("type") == "userMessage"
                and item.get("clientId") == wanted_client_id
            ):
                matches.append(turn)
                break
    if len(matches) > 1:
        raise ProtocolError()
    return matches[0] if matches else None


def select_admission(thread):
    status = thread.get("status")
    if not isinstance(status, dict):
        raise ProtocolError()
    status_type = status.get("type")
    if status_type == "idle":
        return {"mode": "start", "expected_turn_id": None}
    if status_type != "active":
        raise TransportError()
    flags = status.get("activeFlags", [])
    if not isinstance(flags, list) or WAITING_FLAGS.intersection(flags):
        raise TransportError()
    active_turns = [
        turn
        for turn in thread.get("turns", [])
        if isinstance(turn, dict) and turn.get("status") == "inProgress"
    ]
    if len(active_turns) != 1 or not isinstance(active_turns[0].get("id"), str):
        raise TransportError()
    return {"mode": "steer", "expected_turn_id": active_turns[0]["id"]}


def marker_for(batch_id, thread_id, message_id, state, **extra):
    value = {
        "version": 1,
        "batch_id": batch_id,
        "thread_id": thread_id,
        "client_user_message_id": message_id,
        "state": state,
        "updated_at_unix": int(time.time()),
    }
    value.update(extra)
    return value


def validate_marker(marker, batch_id, thread_id, message_id):
    if marker is None:
        return
    if (
        marker.get("version") != 1
        or marker.get("batch_id") != batch_id
        or marker.get("thread_id") != thread_id
        or marker.get("client_user_message_id") != message_id
        or marker.get("state")
        not in {"dispatching", "accepted", "completed", "terminal_failure"}
    ):
        raise ConfigError()


def _server_request_label(method):
    return method if method in SERVER_REQUEST_METHODS else "unknown"


def _attach_failure_context(error, stage, client=None):
    """Attach only allowlisted, secret-free context to an exception."""

    safe_stage = stage if stage in DIAGNOSTIC_STAGES else "unknown"
    method = getattr(client, "last_server_request_method", None)
    try:
        error.nudge_stage = safe_stage
        error.nudge_server_request_method = method
    except Exception:
        pass


def _diagnostic_payload(error, fallback_stage):
    failure_class = type(error).__name__
    if failure_class not in DIAGNOSTIC_FAILURE_CLASSES:
        failure_class = "UnexpectedError"
    stage = getattr(error, "nudge_stage", fallback_stage)
    if stage not in DIAGNOSTIC_STAGES:
        stage = "unknown"
    method = getattr(error, "nudge_server_request_method", None)
    if method is not None and method not in SERVER_REQUEST_METHODS and method != "unknown":
        method = "unknown"
    return {
        "failure_class": failure_class,
        "server_request_method": method,
        "stage": stage,
    }


def _emit_diagnostic(error, fallback_stage):
    print(
        json.dumps(
            _diagnostic_payload(error, fallback_stage),
            sort_keys=True,
            separators=(",", ":"),
        )
    )


class AppServerClient:
    def __init__(
        self,
        command,
        cwd,
        environment=None,
        fail_on_server_request=False,
    ):
        self.process = None
        self.selector = None
        self.app_server_user_agent = None
        self.fail_on_server_request = fail_on_server_request
        try:
            self.process = subprocess.Popen(
                command,
                cwd=str(cwd),
                env=sanitized_environment(environment),
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
                bufsize=0,
                start_new_session=True,
            )
            if self.process.stdin is None or self.process.stdout is None:
                raise TransportError()
            self.selector = selectors.DefaultSelector()
            self.selector.register(self.process.stdout, selectors.EVENT_READ)
            os.set_blocking(self.process.stdout.fileno(), False)
            self.read_buffer = bytearray()
            self.next_request_id = 1
            self.completions = {}
            self.last_server_request_method = None
        except OSError:
            self.close()
            raise TransportError("spawn")
        except BaseException:
            # A TERM can arrive after Popen succeeds but before the caller has
            # received this instance. Own and close that partial process tree
            # here so the caller's finally block is not the only cleanup path.
            self.close()
            raise

    def close(self):
        process = getattr(self, "process", None)
        selector = getattr(self, "selector", None)
        if selector is not None:
            try:
                selector.close()
            except Exception:
                pass
        if process is None:
            return
        if process.stdin is not None:
            try:
                process.stdin.close()
            except OSError:
                pass
        if process.poll() is None:
            try:
                os.killpg(process.pid, signal.SIGTERM)
                process.wait(timeout=3)
            except (OSError, subprocess.TimeoutExpired):
                try:
                    os.killpg(process.pid, signal.SIGKILL)
                    process.wait(timeout=2)
                except (OSError, subprocess.TimeoutExpired):
                    pass
        if process.stdout is not None:
            try:
                process.stdout.close()
            except OSError:
                pass

    def _send(self, message):
        try:
            encoded = json.dumps(message, separators=(",", ":")).encode("utf-8") + b"\n"
            self.process.stdin.write(encoded)
            self.process.stdin.flush()
        except (BrokenPipeError, OSError):
            raise TransportError("write", self.process.poll())

    def _read(self, deadline):
        while True:
            newline = self.read_buffer.find(b"\n")
            if newline >= 0:
                if newline + 1 > MAX_MESSAGE_BYTES:
                    raise ProtocolError()
                line = bytes(self.read_buffer[: newline + 1])
                del self.read_buffer[: newline + 1]
                break
            if len(self.read_buffer) > MAX_MESSAGE_BYTES:
                raise ProtocolError()
            remaining = deadline - time.monotonic()
            if remaining <= 0 or not self.selector.select(remaining):
                raise CompletionTimeout()
            try:
                chunk = os.read(self.process.stdout.fileno(), 64 * 1024)
            except BlockingIOError:
                continue
            except OSError:
                raise TransportError()
            if not chunk:
                if self.read_buffer:
                    raise ProtocolError()
                raise TransportError("eof", self.process.poll())
            self.read_buffer.extend(chunk)
        try:
            message = json.loads(line.decode("utf-8"))
        except (UnicodeDecodeError, ValueError, TypeError):
            raise ProtocolError()
        if not isinstance(message, dict):
            raise ProtocolError()
        return message

    def _respond_to_server_request(self, message):
        method = message.get("method")
        self.last_server_request_method = _server_request_label(method)
        request_id = message.get("id")
        if (
            not isinstance(request_id, (int, str))
            or isinstance(request_id, bool)
            or not isinstance(method, str)
        ):
            raise ProtocolError()
        if method in SERVER_REQUEST_NEGATIVE_RESULTS:
            response = {
                "id": request_id,
                "result": SERVER_REQUEST_NEGATIVE_RESULTS[method],
            }
        else:
            # This covers sensitive known requests that have no documented
            # negative result as well as future unknown request methods.  Do
            # not inspect params or reflect raw method/error content.
            response = {"id": request_id, "error": SERVER_REQUEST_ERROR}
        self._send(response)

    def _observe(self, message):
        if "method" in message and "id" in message:
            self._respond_to_server_request(message)
            return True
        if message.get("method") != "turn/completed":
            return False
        params = message.get("params")
        if not isinstance(params, dict):
            raise ProtocolError()
        thread_id = params.get("threadId")
        turn = params.get("turn")
        if not isinstance(thread_id, str) or not isinstance(turn, dict):
            raise ProtocolError()
        turn_id = turn.get("id")
        turn_status = turn.get("status")
        if isinstance(turn_id, str) and turn_status in TERMINAL_TURN_STATES:
            self.completions[(thread_id, turn_id)] = turn_status
        return False

    def request(self, method, params, timeout):
        request_id = self.next_request_id
        self.next_request_id += 1
        self._send({"method": method, "id": request_id, "params": params})
        deadline = time.monotonic() + timeout
        while True:
            message = self._read(deadline)
            if self._observe(message):
                if self.fail_on_server_request:
                    raise AuthorityRequestDeclined()
                # Request ids are independent in each JSON-RPC direction.  A
                # server request may legally collide with our pending id.
                continue
            if message.get("id") != request_id:
                continue
            if "error" in message:
                raise RequestRejected()
            if "result" not in message:
                raise ProtocolError()
            return message["result"]

    def notify(self, method, params):
        self._send({"method": method, "params": params})

    def initialize(self, timeout):
        result = self.request(
            "initialize",
            {
                "clientInfo": {
                    "name": "meristem_codex_nudge",
                    "title": "Meristem Codex Nudge",
                    "version": "0.1.0",
                },
                "capabilities": {
                    "optOutNotificationMethods": [
                        "item/agentMessage/delta",
                        "item/reasoning/textDelta",
                        "item/reasoning/summaryTextDelta",
                        "item/commandExecution/outputDelta",
                        "item/fileChange/outputDelta",
                    ]
                },
            },
            timeout,
        )
        user_agent = result.get("userAgent") if isinstance(result, dict) else None
        if (
            not isinstance(user_agent, str)
            or not 1 <= len(user_agent) <= 256
            or any(ord(ch) < 0x20 or ord(ch) > 0x7E for ch in user_agent)
        ):
            raise ProtocolError()
        self.app_server_user_agent = user_agent
        self.notify("initialized", {})

    def verify_listener_mcp_config(self, cwd, expected_command, timeout, probe=False):
        result = self.request("config/read", {"cwd": str(Path(cwd).resolve())}, timeout)
        config = result.get("config") if isinstance(result, dict) else None
        origins = result.get("origins") if isinstance(result, dict) else None
        servers = config.get("mcp_servers") if isinstance(config, dict) else None
        features = config.get("features") if isinstance(config, dict) else None
        if not isinstance(servers, dict) or set(servers) != {LISTENER_MCP_SERVER}:
            raise ProtocolError()
        listener = servers.get(LISTENER_MCP_SERVER)
        listener_valid = (
            isinstance(listener, dict)
            and (
                (
                    probe
                    and listener.get("enabled") is False
                    and listener.get("command") == "/usr/bin/false"
                )
                or (
                    not probe
                    and listener.get("enabled") is True
                    and listener.get("command") == expected_command
                    and listener.get("args") == []
                    and listener.get("enabled_tools")
                    == list(LISTENER_MCP_TOOL_ORDER)
                    and listener.get("default_tools_approval_mode") == "approve"
                )
            )
        )
        if (
            not isinstance(features, dict)
            or features.get("apps") is not False
            or not listener_valid
        ):
            raise ProtocolError()
        for origin_key in (
            "features.apps",
            "mcp_servers.meristem_listener.command",
        ):
            origin = origins.get(origin_key) if isinstance(origins, dict) else None
            name = origin.get("name") if isinstance(origin, dict) else None
            version = origin.get("version") if isinstance(origin, dict) else None
            if (
                not isinstance(name, dict)
                or name.get("type") != "sessionFlags"
                or not isinstance(version, str)
                or not version.startswith("sha256:")
                or len(version) > 256
            ):
                raise ProtocolError()

    def verify_listener_mcp_status(
        self, expected_actor_id, timeout, thread_id=None, allow_unstarted=False
    ):
        params = {"detail": "toolsAndAuthOnly"}
        if thread_id is not None:
            params["threadId"] = thread_id
        deadline = time.monotonic() + timeout
        expected_description = LISTENER_TASK_ATTESTATION_PREFIX + expected_actor_id
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise CompletionTimeout()
            result = self.request("mcpServerStatus/list", params, remaining)
            data = result.get("data") if isinstance(result, dict) else None
            if (
                not isinstance(data, list)
                or len(data) != 1
                or result.get("nextCursor") is not None
            ):
                raise ProtocolError()
            server = data[0]
            if (
                not isinstance(server, dict)
                or server.get("name") != LISTENER_MCP_SERVER
                or server.get("authStatus") != "unsupported"
                or server.get("resources") != []
                or server.get("resourceTemplates") != []
            ):
                raise ProtocolError()
            tools = server.get("tools")
            server_info = server.get("serverInfo")
            if server_info is None and tools == {}:
                if allow_unstarted:
                    return
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    raise CompletionTimeout()
                time.sleep(min(0.1, remaining))
                continue
            if (
                not isinstance(server_info, dict)
                or server_info.get("name") != "meristem"
                or server_info.get("description") != expected_description
                or not isinstance(tools, dict)
                or set(tools) != LISTENER_MCP_TOOLS
            ):
                raise ProtocolError()
            for tool_name, tool in tools.items():
                if not isinstance(tool, dict) or tool.get("name") != tool_name:
                    raise ProtocolError()
            return

    def wait_for_completion(self, thread_id, turn_id, timeout):
        wanted = (thread_id, turn_id)
        if self.fail_on_server_request and self.last_server_request_method is not None:
            raise AuthorityRequestDeclined()
        if wanted in self.completions:
            return self.completions[wanted]
        deadline = time.monotonic() + timeout
        while True:
            message = self._read(deadline)
            self._observe(message)
            if self.fail_on_server_request and self.last_server_request_method is not None:
                raise AuthorityRequestDeclined()
            if wanted in self.completions:
                return self.completions[wanted]


def _thread_from_resume(result, thread_id):
    if not isinstance(result, dict) or not isinstance(result.get("thread"), dict):
        raise ProtocolError()
    thread = result["thread"]
    if thread.get("id") != thread_id:
        raise ProtocolError()
    return thread


def _turn_status(turn):
    status = turn.get("status") if isinstance(turn, dict) else None
    return status if status in TERMINAL_TURN_STATES or status == "inProgress" else None


def _record_terminal(marker_path, batch_id, thread_id, message_id, mode, turn_id, status):
    state = "completed" if status == "completed" else "terminal_failure"
    atomic_write_json(
        marker_path,
        marker_for(
            batch_id,
            thread_id,
            message_id,
            state,
            mode=mode,
            turn_id=turn_id,
            turn_status=status,
        ),
    )
    return EXIT_OK if status == "completed" else EXIT_TERMINAL_FAILURE


def deliver(args, command=None, environment=None):
    stage = "validation"
    client = None
    try:
        batch_id, event_count = batch_identity(args.batch_file)
        message_id = client_message_id(batch_id)
        marker_path = Path(args.marker_file)
        marker = load_marker(marker_path)
        validate_marker(marker, batch_id, args.thread_id, message_id)

        if marker and marker["state"] in {"completed", "terminal_failure"}:
            return (
                EXIT_OK
                if marker["state"] == "completed"
                else EXIT_TERMINAL_FAILURE
            )

        command = command or [args.codex_bin, "app-server", "--stdio"]
        stage = "spawn"
        client = AppServerClient(command, args.repo_root, environment)
        stage = "initialize"
        client.initialize(args.request_timeout)
        stage = "resume"
        resume = client.request(
            "thread/resume", {"threadId": args.thread_id}, args.request_timeout
        )
        thread = _thread_from_resume(resume, args.thread_id)
        stage = "reconcile"
        reconciled_turn = find_client_turn(thread, message_id)

        if reconciled_turn is not None:
            turn_id = reconciled_turn.get("id")
            turn_status = _turn_status(reconciled_turn)
            if not isinstance(turn_id, str) or turn_status is None:
                raise ProtocolError()
            mode = marker.get("mode", "reconciled") if marker else "reconciled"
            if turn_status in TERMINAL_TURN_STATES:
                return _record_terminal(
                    marker_path,
                    batch_id,
                    args.thread_id,
                    message_id,
                    mode,
                    turn_id,
                    turn_status,
                )
            atomic_write_json(
                marker_path,
                marker_for(
                    batch_id,
                    args.thread_id,
                    message_id,
                    "accepted",
                    mode=mode,
                    turn_id=turn_id,
                    reconciled=True,
                ),
            )
            stage = "completion"
            status = client.wait_for_completion(
                args.thread_id, turn_id, args.completion_timeout
            )
            return _record_terminal(
                marker_path,
                batch_id,
                args.thread_id,
                message_id,
                mode,
                turn_id,
                status,
            )

        if marker is not None:
            # Absence from resumed history is not proof that a prior dispatch
            # was never admitted. Never resubmit an uncertain admission.
            raise CompletionTimeout()

        admission = select_admission(thread)
        if args.idle_only and admission["mode"] != "start":
            raise TransportError("active-dedicated-thread")
        mode = admission["mode"]
        dispatching = marker_for(
            batch_id,
            args.thread_id,
            message_id,
            "dispatching",
            mode=mode,
            expected_turn_id=admission["expected_turn_id"],
        )
        atomic_write_json(marker_path, dispatching)

        prompt = WAKE_PROMPT.format(batch_id=batch_id, event_count=event_count)
        user_input = [{"type": "text", "text": prompt}]
        stage = "admission"
        if mode == "steer":
            result = client.request(
                "turn/steer",
                {
                    "threadId": args.thread_id,
                    "expectedTurnId": admission["expected_turn_id"],
                    "clientUserMessageId": message_id,
                    "input": user_input,
                },
                args.request_timeout,
            )
            turn_id = result.get("turnId") if isinstance(result, dict) else None
        else:
            result = client.request(
                "turn/start",
                {
                    "threadId": args.thread_id,
                    "clientUserMessageId": message_id,
                    "input": user_input,
                    "sandboxPolicy": {"type": "readOnly", "networkAccess": False},
                    "approvalPolicy": "never",
                    "cwd": str(Path(args.repo_root).resolve()),
                },
                args.request_timeout,
            )
            turn = result.get("turn") if isinstance(result, dict) else None
            turn_id = turn.get("id") if isinstance(turn, dict) else None
        if not isinstance(turn_id, str):
            raise ProtocolError()

        atomic_write_json(
            marker_path,
            marker_for(
                batch_id,
                args.thread_id,
                message_id,
                "accepted",
                mode=mode,
                turn_id=turn_id,
            ),
        )
        stage = "completion"
        status = client.wait_for_completion(
            args.thread_id, turn_id, args.completion_timeout
        )
        return _record_terminal(
            marker_path,
            batch_id,
            args.thread_id,
            message_id,
            mode,
            turn_id,
            status,
        )
    except Exception as error:
        _attach_failure_context(error, stage, client)
        raise
    finally:
        if client is not None:
            client.close()


def activate(args, command=None, environment=None):
    """Drive one event-backed activation without any local delivery journal."""

    stage = "validation"
    client = None
    try:
        validate_listener_paths(args)
        environment = listener_app_server_environment(args, environment)
        activation_id = str(uuid.UUID(args.activation_id))
        work_item_id = str(uuid.UUID(args.work_item_id))
        assignment_event_id = str(uuid.UUID(args.assignment_event_id))
        task_principal_token_id = str(uuid.UUID(args.task_principal_token_id))
        message_id = activation_client_message_id(activation_id)
        command = command or [args.codex_bin, "app-server", "--stdio"]
        stage = "spawn"
        client = AppServerClient(
            command,
            args.repo_root,
            environment,
            fail_on_server_request=True,
        )
        stage = "initialize"
        client.initialize(args.request_timeout)
        expected_mcp_command = str(
            Path(__file__).with_name("codex-listener-mcp-command.sh").resolve()
        )
        client.verify_listener_mcp_config(
            args.repo_root, expected_mcp_command, args.request_timeout
        )
        client.verify_listener_mcp_status(
            task_principal_token_id,
            args.request_timeout,
            allow_unstarted=True,
        )
        stage = "resume"
        try:
            resume = client.request(
                "thread/resume", {"threadId": args.thread_id}, args.request_timeout
            )
        except RequestRejected as error:
            # The desktop app's app-server rejects resume while it owns an
            # active turn. In dispatch mode this is expected backpressure,
            # before any turn/start admission. Reconcile mode remains
            # ambiguous because a prior admission may already exist.
            if args.mode == "dispatch":
                raise TargetBusy() from error
            raise
        thread = _thread_from_resume(resume, args.thread_id)
        client.verify_listener_mcp_status(
            task_principal_token_id, args.request_timeout, args.thread_id
        )
        stage = "reconcile"
        reconciled_turn = find_client_turn(thread, message_id)
        if reconciled_turn is not None:
            # A deterministic client id proves which turn was admitted, but
            # Codex history does not durably prove that an earlier adapter
            # process observed no authority request.  A process could decline
            # one and die before its failed receipt commits.  Never reinterpret
            # that unproven historical turn as successful after restart.
            raise CompletionTimeout()

        if args.mode == "reconcile":
            # Absence is not proof that an uncertain admission never landed.
            raise CompletionTimeout()

        admission = select_admission(thread)
        if admission["mode"] != "start":
            raise TargetBusy()
        prompt = ACTIVATION_WAKE_PROMPT.format(
            activation_id=activation_id,
            work_item_id=work_item_id,
            assignment_event_id=assignment_event_id,
            task_principal_token_id=task_principal_token_id,
        )
        stage = "admission"
        result = client.request(
            "turn/start",
            {
                "threadId": args.thread_id,
                "clientUserMessageId": message_id,
                "input": [{"type": "text", "text": prompt}],
                "sandboxPolicy": {"type": "readOnly", "networkAccess": False},
                "approvalPolicy": "never",
                "cwd": str(Path(args.repo_root).resolve()),
            },
            args.request_timeout,
        )
        turn = result.get("turn") if isinstance(result, dict) else None
        turn_id = turn.get("id") if isinstance(turn, dict) else None
        if not isinstance(turn_id, str):
            raise ProtocolError()
        emit_activation_receipt("accepted", "turn_admitted")
        stage = "completion"
        status = client.wait_for_completion(
            args.thread_id, turn_id, args.completion_timeout
        )
        if status == "completed":
            emit_activation_receipt("completed", "turn_completed")
            return EXIT_OK
        emit_activation_receipt("failed", "turn_terminal_failure")
        return EXIT_TERMINAL_FAILURE
    except AuthorityRequestDeclined:
        emit_activation_receipt("failed", "authority_request_declined")
        return EXIT_TERMINAL_FAILURE
    except Exception as error:
        _attach_failure_context(error, stage, client)
        raise
    finally:
        if client is not None:
            client.close()


def probe(args, command=None, environment=None):
    validate_listener_paths(args)
    environment = listener_app_server_environment(args, environment)
    command = command or [args.codex_bin, "app-server", "--stdio"]
    stage = "spawn"
    client = None
    try:
        client = AppServerClient(command, args.repo_root, environment)
        stage = "initialize"
        client.initialize(args.request_timeout)
        expected_mcp_command = str(
            Path(__file__).with_name("codex-listener-mcp-command.sh").resolve()
        )
        client.verify_listener_mcp_config(
            args.repo_root, expected_mcp_command, args.request_timeout, probe=True
        )
        # A standalone probe verifies app-server/config shape. Exact authenticated
        # task identity and tool inventory are proved inside every activation,
        # where live assignment IDs exist.
        stage = "resume"
        result = client.request(
            "thread/resume", {"threadId": args.thread_id}, args.request_timeout
        )
        thread = _thread_from_resume(result, args.thread_id)
        status = thread.get("status", {})
        status_type = status.get("type") if isinstance(status, dict) else "invalid"
        flags = status.get("activeFlags", []) if isinstance(status, dict) else []
        active_count = sum(
            1
            for turn in thread.get("turns", [])
            if isinstance(turn, dict) and turn.get("status") == "inProgress"
        )
        # This is an allowlisted diagnostic only: no ids, messages, paths,
        # configuration, response errors, or raw protocol content are emitted.
        print(
            json.dumps(
                {
                    "app_server_user_agent": client.app_server_user_agent,
                    "thread_status": status_type,
                    "active_turn_count": active_count,
                    "waiting": bool(WAITING_FLAGS.intersection(flags or [])),
                },
                sort_keys=True,
                separators=(",", ":"),
            )
        )
        return EXIT_OK
    except Exception as error:
        _attach_failure_context(error, stage if stage in DIAGNOSTIC_STAGES else "probe", client)
        raise
    finally:
        if client is not None:
            client.close()


def build_parser():
    parser = argparse.ArgumentParser(description="Safely nudge one Codex task")
    subparsers = parser.add_subparsers(dest="command", required=True)

    def common(subparser):
        subparser.add_argument("--codex-bin", required=True)
        subparser.add_argument("--thread-id", required=True)
        subparser.add_argument("--repo-root", required=True)
        subparser.add_argument("--request-timeout", type=float, default=30.0)
        subparser.add_argument("--diagnostic", action="store_true")

    probe_parser = subparsers.add_parser("probe")
    common(probe_parser)
    probe_parser.add_argument("--listener-codex-home", required=True)
    probe_parser.add_argument("--listener-codex-sqlite-home", required=True)

    deliver_parser = subparsers.add_parser("deliver")
    common(deliver_parser)
    deliver_parser.add_argument("--batch-file", required=True)
    deliver_parser.add_argument("--marker-file", required=True)
    deliver_parser.add_argument("--completion-timeout", type=float, default=1800.0)
    deliver_parser.add_argument(
        "--idle-only",
        action="store_true",
        help="Never steer an unrelated active turn; wait for this task to become idle",
    )

    activate_parser = subparsers.add_parser("activate")
    common(activate_parser)
    activate_parser.add_argument("--listener-codex-home", required=True)
    activate_parser.add_argument("--listener-codex-sqlite-home", required=True)
    activate_parser.add_argument("--activation-id", required=True)
    activate_parser.add_argument("--work-item-id", required=True)
    activate_parser.add_argument("--assignment-event-id", required=True)
    activate_parser.add_argument("--task-principal-token-id", required=True)
    activate_parser.add_argument(
        "--mode", choices=("dispatch", "reconcile"), required=True
    )
    activate_parser.add_argument("--completion-timeout", type=float, default=1800.0)
    return parser


def _validate_args(args):
    repo_root = Path(args.repo_root)
    codex_bin = Path(args.codex_bin)
    activation_ids_valid = True
    if getattr(args, "command", None) == "activate":
        try:
            for value in (
                args.activation_id,
                args.work_item_id,
                args.assignment_event_id,
                args.task_principal_token_id,
            ):
                parsed = uuid.UUID(value)
                if parsed.int == 0 or value != str(parsed):
                    raise ValueError()
        except (ValueError, TypeError, AttributeError):
            activation_ids_valid = False
    if getattr(args, "command", None) in {"activate", "probe"}:
        validate_listener_paths(args)
    if (
        not repo_root.is_absolute()
        or not repo_root.is_dir()
        or not codex_bin.is_absolute()
        or not codex_bin.is_file()
        or not os.access(str(codex_bin), os.X_OK)
        or not args.thread_id
        or not activation_ids_valid
        or args.request_timeout <= 0
        or (hasattr(args, "completion_timeout") and args.completion_timeout <= 0)
    ):
        raise ConfigError()


def main(argv=None):
    def terminate(signum, _frame):
        raise TerminationRequested(130 if signum == signal.SIGINT else 143)

    signal.signal(signal.SIGINT, terminate)
    signal.signal(signal.SIGTERM, terminate)
    args = None
    try:
        args = build_parser().parse_args(argv)
        _validate_args(args)
        if args.command == "probe":
            return probe(args)
        if args.command == "activate":
            return activate(args)
        return deliver(args)
    except ConfigError as error:
        if getattr(args, "diagnostic", False):
            _emit_diagnostic(error, "arguments")
        return EXIT_CONFIG
    except TargetBusy as error:
        if getattr(args, "diagnostic", False):
            _emit_diagnostic(error, "unknown")
        if getattr(args, "command", None) == "activate":
            return EXIT_BUSY
        return EXIT_TRANSIENT
    except (
        CompletionTimeout,
        RequestRejected,
        TransportError,
        ProtocolError,
    ) as error:
        if getattr(args, "diagnostic", False):
            _emit_diagnostic(error, "unknown")
        if getattr(args, "command", None) == "activate":
            stage = getattr(error, "nudge_stage", "unknown")
            if getattr(args, "mode", None) == "reconcile" or stage in {
                "admission",
                "completion",
            }:
                return EXIT_AMBIGUOUS
            return EXIT_TRANSIENT
        marker = None
        if getattr(args, "command", None) == "deliver":
            try:
                marker = load_marker(args.marker_file)
            except ConfigError:
                marker = {"state": "unknown"}
        return EXIT_AMBIGUOUS if marker is not None else EXIT_TRANSIENT
    except Exception as error:
        # The shell caller suppresses stdout/stderr too, but keep the helper
        # secret-silent even when an unexpected library or filesystem failure
        # occurs. Once a marker exists, uncertainty is never replayable.
        if getattr(args, "diagnostic", False):
            _emit_diagnostic(error, "unknown")
        if getattr(args, "command", None) == "activate":
            stage = getattr(error, "nudge_stage", "unknown")
            if getattr(args, "mode", None) == "reconcile" or stage in {
                "admission",
                "completion",
            }:
                return EXIT_AMBIGUOUS
            return EXIT_TRANSIENT
        marker = None
        if getattr(args, "command", None) == "deliver":
            try:
                marker = load_marker(args.marker_file)
            except Exception:
                marker = {"state": "unknown"}
        return EXIT_AMBIGUOUS if marker is not None else EXIT_TRANSIENT
    except TerminationRequested as termination:
        return termination.exit_code


if __name__ == "__main__":
    sys.exit(main())
